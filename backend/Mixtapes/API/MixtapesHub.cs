namespace resonance.Mixtapes.API
{
    using System.Threading.Tasks;
    using Microsoft.AspNetCore.Authorization;
    using Microsoft.AspNetCore.SignalR;

    public static class MixtapesHubMethods
    {
        public static readonly string Updated = "UPDATED";
    }

    public static class MixtapesHubExtensions
    {
        public static Task BroadcastUpdatedAsync(this IHubContext<MixtapesHub> hub)
            => hub.Clients.All.SendAsync(MixtapesHubMethods.Updated);
    }

    [Authorize(Policy = AuthPolicy.Any)]
    public class MixtapesHub : Hub
    {
    }
}
