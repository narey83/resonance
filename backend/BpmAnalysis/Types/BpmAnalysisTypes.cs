namespace resonance.BpmAnalysis
{
    /// <summary>State of an in-progress BPM analysis scan.</summary>
    public record BpmScanState(
        bool Scanning,
        bool Completed,
        bool Cancelled,
        int Total,
        int Analysed,
        int Skipped,
        int Failed,
        double Progress,
        int InFlight = 0);

    /// <summary>BPM status for a single track.</summary>
    public record TrackBpmInfo(
        string MaskedFilename,
        string OriginalFilename,
        string Directory,
        string Filename,
        string Extension,
        uint? Bpm,
        bool HasBpm,
        string Artist,
        string Title,
        string Album);

    /// <summary>Request body for starting a BPM analysis scan.</summary>
    public record BpmScanRequest(
        bool SkipTagged = true,
        bool ResetAll = false,
        string Algorithm = "audioAnalysis",
        int Workers = 2,
        string[] OnlyFilenames = null);
}
