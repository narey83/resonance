namespace resonance.Authentication;

using System;

// A device's FCM registration token, keyed by (Username, DeviceId) so a device that re-registers
// (app reinstall, token rotation) upserts in place rather than accumulating duplicate rows.
public class PushToken
{
    public Guid Id { get; set; } = Guid.NewGuid();
    public string Username { get; set; }
    public string DeviceId { get; set; }
    public string Token { get; set; }
    public string Platform { get; set; }
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
}
