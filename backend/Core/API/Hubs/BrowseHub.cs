namespace resonance.Core.API
{
    using System.Collections.Generic;
    using System.Threading.Tasks;
    using Microsoft.AspNetCore.Authorization;
    using Microsoft.AspNetCore.SignalR;

    public static class BrowseHubMethods
    {
        /// <summary>
        ///     Fired whenever the browse history changes (a user was browsed or an
        ///     entry was removed); payload is the full updated history list.
        /// </summary>
        public static readonly string History = "HISTORY";
    }

    public static class BrowseHubExtensions
    {
        public static Task BroadcastHistoryAsync(this IHubContext<BrowseHub> hub, IReadOnlyList<string> history)
            => hub.Clients.All.SendAsync(BrowseHubMethods.History, history);
    }

    /// <summary>
    ///     Pushes browse-history changes to all connected clients so web and mobile
    ///     stay in sync in real time.
    /// </summary>
    [Authorize(Policy = AuthPolicy.Any)]
    public class BrowseHub : Hub
    {
    }
}
