namespace resonance.Migrations;

using Microsoft.Data.Sqlite;
using Serilog;

/// <summary>
///     Adds a Role column to the Users table in resonance-users.db.
///     Existing users are defaulted to 'Administrator'.
/// </summary>
public class Z2026_05_27_UserRolesMigration : IMigration
{
    public Z2026_05_27_UserRolesMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Users];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        try
        {
            using var conn = new SqliteConnection(ConnectionString);
            conn.Open();
            using var cmd = new SqliteCommand("PRAGMA table_info(Users);", conn);
            using var reader = cmd.ExecuteReader();
            while (reader.Read())
            {
                if (reader.GetString(1) == "Role")
                {
                    return false;
                }
            }

            return true;
        }
        catch
        {
            return false;
        }
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_05_27_UserRolesMigration));
            return;
        }

        using var conn = new SqliteConnection(ConnectionString);
        conn.Open();

        using var cmd = new SqliteCommand(
            "ALTER TABLE Users ADD COLUMN Role TEXT NOT NULL DEFAULT 'Administrator';",
            conn);
        cmd.ExecuteNonQuery();

        Log.Information("> Added Role column to Users table; existing users defaulted to 'Administrator'");
    }
}
