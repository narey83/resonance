namespace resonance.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using Serilog;

/// <summary>
///     Adds an index on Events(Timestamp DESC) to speed up the ordered, paginated event queries on the overview page.
/// </summary>
public class Z2026_06_07_EventTimestampIndexMigration : IMigration
{
    public Z2026_06_07_EventTimestampIndexMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Events];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var idxes = SchemaInspector.GetDatabaseIndexes(ConnectionString);
        if (!idxes.TryGetValue("Events", out var eventIdxes))
        {
            return true;
        }

        return !eventIdxes.Any(c => c.Name.Equals("IDX_Events_Timestamp", StringComparison.OrdinalIgnoreCase));
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_06_07_EventTimestampIndexMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Adding index on Events(Timestamp DESC)...");

            using var command = new SqliteCommand(
                "CREATE INDEX IF NOT EXISTS IDX_Events_Timestamp ON Events (Timestamp DESC)",
                connection,
                transaction);
            command.ExecuteNonQuery();

            Log.Information("> Index created");
            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
