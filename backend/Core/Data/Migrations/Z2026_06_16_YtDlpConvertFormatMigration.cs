namespace resonance.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using Resonance.Integrations.YtDlp.Types;
using Serilog;

/// <summary>
///     Adds the ConvertOnCompletionFormatOverride column to the yt-dlp Jobs table.
/// </summary>
public class Z2026_06_16_YtDlpConvertFormatMigration : IMigration
{
    public Z2026_06_16_YtDlpConvertFormatMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.YtDlp];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var schema = SchemaInspector.GetDatabaseSchema(ConnectionString);
        if (!schema.TryGetValue("Jobs", out var columns))
        {
            // Table doesn't exist yet (fresh DB) — EnsureCreated will build it with the column.
            return false;
        }

        return !columns.Any(c => c.Name == nameof(YtDlpJob.ConvertOnCompletionFormatOverride));
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_06_16_YtDlpConvertFormatMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Adding ConvertOnCompletionFormatOverride column to the yt-dlp Jobs table...");

            using var command = new SqliteCommand(
                "ALTER TABLE Jobs ADD COLUMN ConvertOnCompletionFormatOverride TEXT NULL;",
                connection,
                transaction);

            command.ExecuteNonQuery();

            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
