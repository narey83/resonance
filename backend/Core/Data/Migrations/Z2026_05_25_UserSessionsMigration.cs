namespace resonance.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using Serilog;

/// <summary>
///     Creates the Sessions table in the users database for refresh token / session management.
/// </summary>
public class Z2026_05_25_UserSessionsMigration : IMigration
{
    public Z2026_05_25_UserSessionsMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Users];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var schema = SchemaInspector.GetDatabaseSchema(ConnectionString);
        return !schema.ContainsKey("Sessions");
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_05_25_UserSessionsMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Creating Sessions table...");

            using var command = new SqliteCommand(
                """
                CREATE TABLE Sessions (
                    Id   TEXT NOT NULL PRIMARY KEY,
                    Username          TEXT NOT NULL,
                    RefreshTokenHash  TEXT NOT NULL,
                    DeviceName        TEXT NULL,
                    IsRevoked         INTEGER NOT NULL DEFAULT 0,
                    CreatedAt         TEXT NOT NULL,
                    LastUsedAt        TEXT NOT NULL,
                    ExpiresAt         TEXT NOT NULL
                );
                CREATE INDEX IX_Sessions_Username         ON Sessions (Username);
                CREATE INDEX IX_Sessions_RefreshTokenHash ON Sessions (RefreshTokenHash);
                """,
                connection,
                transaction);

            command.ExecuteNonQuery();

            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
