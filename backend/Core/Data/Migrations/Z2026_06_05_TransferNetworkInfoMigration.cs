namespace resonance.Migrations;

using System;
using Microsoft.Data.Sqlite;
using Serilog;

/// <summary>
///     Creates a TransferNetworkInfo table to store IP/geo data per transfer.
/// </summary>
public class Z2026_06_05_TransferNetworkInfoMigration : IMigration
{
    public Z2026_06_05_TransferNetworkInfoMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Transfers];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var tables = SchemaInspector.GetDatabaseSchema(ConnectionString);
        return !tables.ContainsKey("TransferNetworkInfo");
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_06_05_TransferNetworkInfoMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Creating TransferNetworkInfo table...");

            using var cmd = new SqliteCommand(@"
                CREATE TABLE TransferNetworkInfo (
                    Username TEXT NOT NULL,
                    IpAddress TEXT NOT NULL,
                    Country TEXT NULL,
                    City TEXT NULL,
                    IsVpn INTEGER NOT NULL DEFAULT 0,
                    LastSeen TEXT NOT NULL,
                    PRIMARY KEY (Username)
                )", connection, transaction);

            cmd.ExecuteNonQuery();

            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
