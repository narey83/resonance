namespace resonance.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using resonance.Transfers;
using Serilog;

/// <summary>
///     Adds DestinationFolder column to the Transfers table.
/// </summary>
public class Z2026_05_24_TransferDestinationFolderMigration : IMigration
{
    public Z2026_05_24_TransferDestinationFolderMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.Transfers];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var columns = SchemaInspector.GetDatabaseSchema(ConnectionString)["Transfers"];
        return !columns.Any(c => c.Name == nameof(Transfer.DestinationFolder));
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_05_24_TransferDestinationFolderMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Adding DestinationFolder column to the Transfers table...");

            using var command = new SqliteCommand(
                "ALTER TABLE Transfers ADD COLUMN DestinationFolder TEXT NULL;",
                connection,
                transaction);

            command.ExecuteNonQuery();

            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
