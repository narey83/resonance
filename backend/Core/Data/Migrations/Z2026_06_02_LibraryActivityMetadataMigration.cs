namespace resonance.Migrations;

using System;
using System.Linq;
using Microsoft.Data.Sqlite;
using Serilog;

public class Z2026_06_02_LibraryActivityMetadataMigration : IMigration
{
    public Z2026_06_02_LibraryActivityMetadataMigration(ConnectionStringDictionary connectionStrings)
    {
        ConnectionString = connectionStrings[Database.LibraryActivity];
    }

    private ILogger Log { get; } = Serilog.Log.ForContext("SourceContext", Logs.Database);
    private string ConnectionString { get; }

    public bool NeedsToBeApplied()
    {
        var schema = SchemaInspector.GetDatabaseSchema(ConnectionString);
        return schema.ContainsKey("PlayHistory") &&
               !schema["PlayHistory"].Any(c => c.Name == "Title");
    }

    public void Apply()
    {
        if (!NeedsToBeApplied())
        {
            Log.Information("> Migration {Name} is not necessary or has already been applied", nameof(Z2026_06_02_LibraryActivityMetadataMigration));
            return;
        }

        using var connection = new SqliteConnection(ConnectionString);
        connection.Open();

        using var transaction = connection.BeginTransaction();

        try
        {
            Log.Information("> Adding Title, Artist, Folder columns to PlayHistory...");

            using var ph = new SqliteCommand(@"
                ALTER TABLE PlayHistory ADD COLUMN Title  TEXT NOT NULL DEFAULT '';
                ALTER TABLE PlayHistory ADD COLUMN Artist TEXT NOT NULL DEFAULT '';
                ALTER TABLE PlayHistory ADD COLUMN Folder TEXT NOT NULL DEFAULT '';",
                connection, transaction);
            ph.ExecuteNonQuery();

            Log.Information("> Adding Title, Artist, Folder columns to LovedTracks...");

            using var lt = new SqliteCommand(@"
                ALTER TABLE LovedTracks ADD COLUMN Title  TEXT NOT NULL DEFAULT '';
                ALTER TABLE LovedTracks ADD COLUMN Artist TEXT NOT NULL DEFAULT '';
                ALTER TABLE LovedTracks ADD COLUMN Folder TEXT NOT NULL DEFAULT '';",
                connection, transaction);
            lt.ExecuteNonQuery();

            transaction.Commit();
            Log.Information("> Done!");
        }
        catch (Exception)
        {
            transaction.Rollback();
            throw;
        }
    }
}
