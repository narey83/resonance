namespace resonance.LinkPreview.API
{
    /// <summary>
    ///     Metadata scraped from a linked page's HTML for a chat-message link preview card.
    /// </summary>
    public class LinkPreviewResponse
    {
        /// <summary>
        ///     Gets the URL the preview was generated for.
        /// </summary>
        public string Url { get; init; }

        /// <summary>
        ///     Gets the page title.
        /// </summary>
        public string Title { get; init; }

        /// <summary>
        ///     Gets the page description.
        /// </summary>
        public string Description { get; init; }

        /// <summary>
        ///     Gets the absolute URL of the preview image, if the page published one.
        /// </summary>
        public string ImageUrl { get; init; }

        /// <summary>
        ///     Gets the site name, if the page published one.
        /// </summary>
        public string SiteName { get; init; }
    }
}
