namespace resonance.KeyAnalysis
{
    using System;

    /// <summary>State of an in-progress key analysis scan.</summary>
    public record KeyScanState(
        bool Scanning,
        bool Completed,
        bool Cancelled,
        int Total,
        int Analysed,
        int Skipped,
        int Failed,
        double Progress,
        int InFlight = 0);

    /// <summary>Key status for a single track.</summary>
    public record TrackKeyInfo(
        string MaskedFilename,
        string OriginalFilename,
        string Directory,
        string Filename,
        string Extension,
        string Key,
        bool HasKey,
        string Artist,
        string Title,
        string Album);

    /// <summary>Request body for starting a key analysis scan.</summary>
    public record KeyScanRequest(
        bool SkipTagged = true,
        bool ResetAll = false,
        string Algorithm = "audioAnalysis",
        int Workers = 2,
        string[] OnlyFilenames = null);
}
