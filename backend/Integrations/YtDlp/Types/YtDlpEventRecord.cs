namespace Resonance.Integrations.YtDlp.Types;

using System;

/// <summary>
///     A persisted job-log event. The volatile <see cref="YtDlpEvent" /> record is what is
///     broadcast to clients; this is its durable counterpart, kept until the user clears it so the
///     Events pane survives restarts and buffer eviction. Only meaningful (non-"raw") events are
///     stored — the high-volume raw yt-dlp stderr/progress lines stay in the in-memory buffer only.
/// </summary>
public class YtDlpEventRecord
{
    public long Id { get; set; }

    public DateTime Timestamp { get; set; }

    public Guid? JobId { get; set; }

    public string? JobTitle { get; set; }

    public string Level { get; set; } = "info";

    public string Message { get; set; } = string.Empty;
}
