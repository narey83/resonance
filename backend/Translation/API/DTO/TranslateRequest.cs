namespace resonance.Translation.API
{
    using System.Collections.Generic;

    /// <summary>
    ///     A request to translate one or more pieces of text.
    /// </summary>
    public class TranslateRequest
    {
        /// <summary>
        ///     Gets or sets the texts to translate. Results are returned in the same order.
        /// </summary>
        public List<string> Texts { get; set; }

        /// <summary>
        ///     Gets or sets the target language code (e.g. EN, DE, FR). When omitted, the server default is used.
        /// </summary>
        public string? TargetLanguage { get; set; }
    }
}
