namespace resonance.TagSanitization.API
{
    using System.Threading.Tasks;
    using Asp.Versioning;
    using Microsoft.AspNetCore.Authorization;
    using Microsoft.AspNetCore.Mvc;

    /// <summary>
    ///     Tag sanitization — consolidate all ID3 tag versions into a single
    ///     clean ID3v2.3 tag across the local share.
    /// </summary>
    [ApiController]
    [ApiVersion("0")]
    [Produces("application/json")]
    [Consumes("application/json")]
    [Route("api/v{version:apiVersion}/[controller]")]
    public class TagSanitizationController : ControllerBase
    {
        public TagSanitizationController(ITagSanitizationService service)
        {
            Service = service;
        }

        private ITagSanitizationService Service { get; }

        /// <summary>Returns the current scan state, including recent results.</summary>
        /// <returns></returns>
        [HttpGet("scan")]
        [Authorize(Policy = AuthPolicy.Any)]
        [ProducesResponseType(typeof(TagSanitizationState), 200)]
        public IActionResult GetScanState() => Ok(Service.ScanState);

        /// <summary>Starts a tag sanitization scan.</summary>
        /// <returns>A <see cref="Task"/> representing the asynchronous operation.</returns>
        [HttpPost("scan")]
        [Authorize(Policy = AuthPolicy.Any)]
        [ProducesResponseType(202)]
        [ProducesResponseType(409)]
        public async Task<IActionResult> StartScan([FromBody] TagSanitizationRequest request)
        {
            try
            {
                _ = Service.StartScanAsync(request ?? new TagSanitizationRequest());
                await Task.Yield();
                return Accepted();
            }
            catch (System.InvalidOperationException)
            {
                return Conflict("A tag sanitization scan is already in progress.");
            }
        }

        /// <summary>Cancels the current scan.</summary>
        /// <returns></returns>
        [HttpDelete("scan")]
        [Authorize(Policy = AuthPolicy.Any)]
        [ProducesResponseType(204)]
        [ProducesResponseType(404)]
        public IActionResult CancelScan()
        {
            if (Service.CancelScan())
            {
                return NoContent();
            }

            return NotFound("No scan is in progress.");
        }
    }
}
