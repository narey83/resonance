namespace resonance.TagSanitization
{
    using System.Collections.Generic;

    /// <summary>Live state of a tag sanitization scan.</summary>
    public record TagSanitizationState(
        bool Scanning,
        bool Completed,
        bool Cancelled,
        int Total,
        int Processed,
        int Sanitized,
        int Skipped,
        int Failed,
        double Progress,
        IReadOnlyList<FileConsolidationResult> Results);

    /// <summary>Parameters for starting a sanitization scan.</summary>
    public record TagSanitizationRequest(
        int Workers = 2,
        bool DryRun = false);

    /// <summary>Per-file result from consolidation (or dry-run analysis).</summary>
    public record FileConsolidationResult(
        string MaskedFilename,
        string Filename,
        string Directory,
        bool Changed,
        string[] Changes);
}
