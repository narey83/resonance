namespace resonance.Common
{
    using System.IO;

    /// <summary>Identifies transient file sharing conflicts without hiding other storage failures.</summary>
    internal static class FileSharingViolation
    {
        /// <summary>Checks the native error code rather than a localized exception message.</summary>
        /// <param name="exception">The file operation failure.</param>
        /// <returns>Whether the failure reports a sharing violation, lock violation or advisory-lock conflict.</returns>
        internal static bool Is(IOException exception)
        {
            // Windows sharing/lock violations and EAGAIN from advisory file locking.
            // Darwin uses 35 for EAGAIN; Linux uses 11.
            var code = exception.HResult & 0xFFFF;
            return code is 32 or 33 or 11 || (System.OperatingSystem.IsMacOS() && code == 35);
        }
    }
}
