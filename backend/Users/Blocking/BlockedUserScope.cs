namespace resonance.Users.Blocking;

/// <summary>
///     The interaction being guarded by a blocked-user check; each scope maps to
///     a toggle in <see cref="BlockedUserOptions"/>.
/// </summary>
public enum BlockedUserScope
{
    /// <summary>
    ///     File transfers (enqueue requests, queue position, downloads).
    /// </summary>
    Transfers,

    /// <summary>
    ///     Browse and directory content requests.
    /// </summary>
    Browse,

    /// <summary>
    ///     Responses to incoming search requests.
    /// </summary>
    SearchResponses,

    /// <summary>
    ///     Private messages, sent and received.
    /// </summary>
    PrivateMessages,

    /// <summary>
    ///     Chat room messages received.
    /// </summary>
    RoomMessages,

    /// <summary>
    ///     Search results received from blocked users.
    /// </summary>
    SearchResults,
}
