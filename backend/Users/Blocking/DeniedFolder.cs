namespace resonance.Users.Blocking;

using System;

/// <summary>
///     A remote folder permanently denied to a specific Soulseek user; unlike a plain upload
///     cancellation, a denied folder is rejected at enqueue time so the user can't simply
///     re-request the same files.
/// </summary>
public class DeniedFolder
{
    /// <summary>
    ///     Gets or sets the username the folder is denied to.
    /// </summary>
    public string Username { get; set; }

    /// <summary>
    ///     Gets or sets the remote directory that is denied.
    /// </summary>
    public string Directory { get; set; }

    /// <summary>
    ///     Gets or sets the time at which the folder was denied.
    /// </summary>
    public DateTime DeniedAt { get; set; }

    /// <summary>
    ///     Gets or sets an optional note recorded when the folder was denied.
    /// </summary>
    public string Reason { get; set; }
}
