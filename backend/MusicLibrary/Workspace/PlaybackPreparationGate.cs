namespace resonance.MusicLibrary.Workspace;

/// <summary>
/// Gives playback priority while allowing one background preparation job every two minutes.
/// </summary>
internal sealed class PlaybackPreparationGate
{
    private long nextAllowedAt;

    /// <summary>
    /// Determines whether automatic preparation should wait during active playback.
    /// </summary>
    /// <param name="playing">Whether a recent playback lease is active.</param>
    /// <param name="now">Current time in milliseconds.</param>
    /// <returns>True when preparation must wait.</returns>
    internal bool ShouldWait(bool playing, long now)
    {
        if (!playing)
        {
            nextAllowedAt = 0;
            return false;
        }

        if (nextAllowedAt == 0)
        {
            nextAllowedAt = now + 120_000;
        }

        if (now < nextAllowedAt)
        {
            return true;
        }

        nextAllowedAt = now + 120_000;
        return false;
    }
}
