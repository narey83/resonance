namespace resonance.MusicLibrary.Converter.Types;

using System;
using System.Collections.Generic;

public enum ConverterJobState
{
    Running,
    Completed,
    Cancelled,
}

/// <summary>
///     In-memory state for a library conversion run. Conversions are transient and not persisted.
/// </summary>
public sealed class ConverterJob
{
    public Guid Id { get; init; } = Guid.NewGuid();
    public string Format { get; init; } = string.Empty;
    public int Quality { get; init; }
    public ConverterJobState State { get; set; } = ConverterJobState.Running;
    public int Total { get; set; }
    public int Converted { get; set; }
    public int Failed { get; set; }
    public int Skipped { get; set; }
    public string? CurrentFile { get; set; }
    public DateTime StartedAt { get; init; } = DateTime.UtcNow;
    public DateTime? CompletedAt { get; set; }

    // Bounded list of human-readable failure messages for the UI.
    public List<string> Errors { get; } = new();
}
