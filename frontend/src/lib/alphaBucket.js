// Which letter of the A–Z rail a value belongs under: first character of the trimmed value,
// uppercased, with everything outside A–Z collected under '#'. Must stay in step with the
// backend's AlphaBucket (MusicLibraryController) and the SQL FirstChar/AlphaLetters
// (MusicRepository), so a letter means the same thing whether the list is narrowed by the
// server or here. Was copy-pasted into ArtistsView, FolderView and TrackTable.
export const alphaKey = (value) => {
  const first = value?.trim()?.[0]?.toUpperCase();
  return first >= 'A' && first <= 'Z' ? first : '#';
};
