// Live signal that a peer transfer completed. The telemetry user list only
// counts finished transfers (EndedAt IS NOT NULL), so these are exactly the
// moments a user row can appear or update — letting views refresh instantly
// instead of waiting for their poll interval.

const target = new EventTarget();

export const emitTransferComplete = (detail) => {
  target.dispatchEvent(new CustomEvent('transfer-complete', { detail }));
};

export const onTransferComplete = (handler) => {
  const listener = (e) => handler(e.detail);
  target.addEventListener('transfer-complete', listener);
  return () => target.removeEventListener('transfer-complete', listener);
};
