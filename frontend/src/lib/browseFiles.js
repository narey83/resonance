import { extractMetadata } from './searchMetadata';

// Turns a user's raw browse response (a flat list of directories, each with its
// own direct files) into a single flat list of every file they share, tagged
// with parsed metadata and its owning directory path — the shape BrowseResults
// needs to filter/group across the whole share at once, like search results.
export const flattenDirectories = (directories, separator) => {
  const files = [];

  for (const d of directories) {
    for (const f of d.files ?? []) {
      const fullPath = `${d.name}${separator}${f.filename}`;
      files.push({
        ...f,
        fullPath,
        _directory: d.name,
        locked: Boolean(d.locked),
        ...extractMetadata(fullPath),
      });
    }
  }

  return files;
};
