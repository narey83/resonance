import api from './api';

export const getNetworkInfo = async () => (await api.get('/network/info')).data;

// Forward cancellation without changing the network API query.
export const lookupIp = async (ip, { signal } = {}) =>
  (await api.get(`/network/lookup?ip=${encodeURIComponent(ip)}`, { signal }))
    .data;

export const batchLookup = async (ips, { signal } = {}) =>
  (await api.post('/network/batch', ips, { signal })).data;
