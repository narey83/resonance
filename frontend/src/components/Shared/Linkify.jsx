import { linkifyText } from '../Chat/chatUtils';
import React from 'react';

// Renders message text with any http(s) URLs turned into clickable links.
// Text is split into plain-string / `{ url }` segments and rendered as
// separate React nodes, never through dangerouslySetInnerHTML.
const Linkify = ({ text }) =>
  linkifyText(text).map((part, index) =>
    typeof part === 'string' ? (
      // eslint-disable-next-line react/no-array-index-key
      <React.Fragment key={index}>{part}</React.Fragment>
    ) : (
      <a
        className="chat-inline-link"
        href={part.url}
        // eslint-disable-next-line react/no-array-index-key
        key={index}
        onClick={(e) => e.stopPropagation()}
        rel="noopener noreferrer"
        target="_blank"
      >
        {part.url}
      </a>
    ),
  );

export default Linkify;
