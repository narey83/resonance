import { RotateCcw } from 'lucide-react';
import React from 'react';

// Sort, column filter and letter each live in their own control, so a view can end up narrowed
// three different ways with no single place to undo it — and on a paged list a stray filter
// looks like a library that has lost most of its rows. Shows only when there is something to
// undo, so the default view stays uncluttered.
const ResetViewButton = ({ hidden, onReset }) =>
  hidden ? null : (
    <button
      className="jb-reset-view"
      onClick={onReset}
      title="Clear sorting, filters and the letter jump"
      type="button"
    >
      <RotateCcw size={11} />
      Reset view
    </button>
  );

export default ResetViewButton;
