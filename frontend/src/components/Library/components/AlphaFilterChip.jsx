import { X } from 'lucide-react';
import React from 'react';

// On a server-paged list the A-Z rail narrows the query rather than scrolling to a row, so the
// rest of the library disappears until it's cleared. Without something on screen saying so,
// that reads as "my library lost most of its artists". This is that something.
const AlphaFilterChip = ({ letter, onClear }) =>
  letter ? (
    <button
      className="jb-alpha-chip"
      onClick={onClear}
      title="Show all letters"
      type="button"
    >
      Starting with <strong>{letter}</strong>
      <X size={11} />
    </button>
  ) : null;

export default AlphaFilterChip;
