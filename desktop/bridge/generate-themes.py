#!/usr/bin/env python3
"""Generate Bridge palettes from the web app's theme tokens. Run with --check in CI."""
import argparse
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
components = root / "frontend/src/components"
if not components.exists():
    components = Path(__file__).resolve().parent / "theme-sources"
app = (components / "App.css").read_text()
workspace = (components / "MusicWorkspace.css").read_text()
tokens = ("bg-primary", "bg-surface", "bg-elevated", "border", "text-primary",
          "text-muted", "accent", "accent-hover", "success", "danger", "nav-bg",
          "nav-item-active-bg", "on-accent")

def values(source, selector):
    match = re.search(re.escape(selector) + r"\s*\{([^}]+)\}", source)
    if not match:
        raise ValueError("Missing theme: " + selector)
    return dict(re.findall(r"--([a-z-]+):\s*([^;]+);", match[1]))

base = values(app, ":root")
base.update({"nav-bg": "var(--bg-surface)", "on-accent": "#fff"})
base.update(values(workspace, ".dj-workspace"))
dark_workspace = values(workspace, ":root:is(.dark,.dim,.amoled) .dj-workspace")
palettes = {
    "light": base,
    "amoled": {**base, **values(app, ":root.amoled"), **dark_workspace,
               "on-accent": dark_workspace["bg-primary"]},
}
for name in ("midnight", "violet", "ember"):
    palettes[name] = {**base, **values(workspace, ":root." + name + ", :root." + name + " .dj-workspace")}
css = "/* Generated by generate-themes.py from Resonance UI tokens. Do not edit. */\n"
for name, palette in palettes.items():
    css += ':root[data-theme="' + name + '"] {\n  color-scheme: ' + ("light" if name == "light" else "dark") + ";\n"
    for token in tokens:
        if token in palette:
            css += "  --" + token + ": " + palette[token] + ";\n"
    css += "}\n"
target = Path(__file__).with_name("themes.css")
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != css:
        raise SystemExit("Bridge palettes are stale. Run desktop/bridge/generate-themes.py")
else:
    target.write_text(css)
