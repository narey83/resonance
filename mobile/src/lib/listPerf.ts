// Shared FlatList virtualization tuning for the (potentially large) lists across the
// app. These props are height-agnostic, so they're safe to spread onto any list
// regardless of row layout or ListHeaderComponent — they cap how many cells are
// mounted at once and let Android detach off-screen views, which is the main
// scroll-jank win on lower-end devices.
//
// getItemLayout is deliberately NOT included here: it needs an exact per-list row
// height, and several lists carry a header where a hardcoded offset breaks
// scrollToIndex / initial layout. Add it locally only on a fixed-height, header-less
// list where it's demonstrably correct.
export const LIST_PERF_PROPS = {
  removeClippedSubviews: true,
  initialNumToRender: 12,
  maxToRenderPerBatch: 10,
  windowSize: 9,
  updateCellsBatchingPeriod: 50,
} as const;
