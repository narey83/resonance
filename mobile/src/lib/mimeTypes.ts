const CONTENT_TYPES: Record<string, string> = {
  mp3:  'audio/mpeg',
  flac: 'audio/flac',
  ogg:  'audio/ogg',
  opus: 'audio/ogg',
  wav:  'audio/wav',
  m4a:  'audio/mp4',
  aac:  'audio/aac',
  wma:  'audio/x-ms-wma',
  aiff: 'audio/aiff',
  aif:  'audio/aiff',
};

export const contentTypeFor = (path: string | null | undefined): string => {
  if (!path) return 'audio/mpeg';
  const cleanPath = path.split('?')[0];
  const ext = cleanPath.split('.').pop()?.toLowerCase() ?? '';
  return CONTENT_TYPES[ext] ?? 'audio/mpeg';
};
