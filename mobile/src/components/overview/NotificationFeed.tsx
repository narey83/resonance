// Simplified mobile counterpart of the web's NotificationFeed: a plain
// type + relative-time list, without per-type icons/click-through links
// (those route into web-only pages like /downloads or /chat).

import React from 'react';
import { ThemeColors } from '../../theme';
import { EventRecord } from '../../api/events';
import { Card, EmptyState, fmtDate, StatRow } from './shared';

export default function NotificationFeed({ events, colors }: { events: EventRecord[]; colors: ThemeColors }) {
  if (events.length === 0) {
    return <Card colors={colors}><EmptyState text="No recent activity." colors={colors} /></Card>;
  }

  return (
    <Card colors={colors}>
      {events.map((e, i) => (
        <StatRow
          key={e.id}
          label={e.type}
          value={fmtDate(e.timestamp)}
          colors={colors}
          last={i === events.length - 1}
        />
      ))}
    </Card>
  );
}
