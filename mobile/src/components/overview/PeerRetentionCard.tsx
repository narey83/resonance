import React from 'react';
import { ThemeColors } from '../../theme';
import { PeerRetention } from '../../api/analytics';
import { BarRow, Card, EmptyState, fmtNum } from './shared';

export default function PeerRetentionCard({ data, colors }: { data: PeerRetention | null; colors: ThemeColors }) {
  const total = (data?.newPeers ?? 0) + (data?.returningPeers ?? 0);
  if (!data || total === 0) {
    return <Card colors={colors}><EmptyState text="No peer activity in this window." colors={colors} /></Card>;
  }

  return (
    <Card colors={colors}>
      <BarRow label="New peers" value={fmtNum(data.newPeers)} fraction={data.newPeers / total} colors={colors} />
      <BarRow
        label="Returning peers"
        value={fmtNum(data.returningPeers)}
        fraction={data.returningPeers / total}
        color={colors.success}
        colors={colors}
        last
      />
    </Card>
  );
}
