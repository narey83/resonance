import React from 'react';
import { ThemeColors } from '../../theme';
import { QueueWaitStats } from '../../api/analytics';
import { Card, EmptyState, StatRow } from './shared';

const fmtSeconds = (s: number): string => {
  if (!Number.isFinite(s)) return '—';
  if (s < 60) return `${s.toFixed(1)}s`;
  if (s < 3600) return `${(s / 60).toFixed(1)}m`;
  return `${(s / 3600).toFixed(1)}h`;
};

export default function QueueWaitCard({ stats, colors }: { stats: QueueWaitStats | null; colors: ThemeColors }) {
  if (!stats || stats.count === 0) {
    return <Card colors={colors}><EmptyState text="No queued uploads in this window." colors={colors} /></Card>;
  }

  return (
    <Card colors={colors}>
      <StatRow label="Median (p50)" value={fmtSeconds(stats.p50)} colors={colors} />
      <StatRow label="p90" value={fmtSeconds(stats.p90)} colors={colors} />
      <StatRow label="p99" value={fmtSeconds(stats.p99)} colors={colors} />
      <StatRow label="Max" value={fmtSeconds(stats.max)} colors={colors} />
      <StatRow label="Average" value={fmtSeconds(stats.avg)} colors={colors} last />
    </Card>
  );
}
