import React from 'react';
import { ThemeColors } from '../../theme';
import { BarRow, Card, fmtNum, fmtPct } from './shared';

export default function CoverageCard({
  totalFiles,
  uploadedFiles,
  colors,
}: {
  totalFiles:    number;
  uploadedFiles: number;
  colors:        ThemeColors;
}) {
  const fraction = totalFiles > 0 ? uploadedFiles / totalFiles : 0;
  return (
    <Card colors={colors}>
      <BarRow
        label="Catalog reach"
        value={`${fmtNum(uploadedFiles)} / ${fmtNum(totalFiles)} (${fmtPct(fraction)})`}
        fraction={fraction}
        colors={colors}
        last
      />
    </Card>
  );
}
