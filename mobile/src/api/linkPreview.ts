import { apiClient } from './client';

export interface LinkPreview {
  url: string;
  title: string | null;
  description: string | null;
  imageUrl: string | null;
  siteName: string | null;
}

// Keyed by URL so the same link posted in multiple messages, or the same
// message re-rendered on a list re-mount, only ever triggers one fetch.
const cache = new Map<string, Promise<LinkPreview | null>>();

export const getLinkPreview = (url: string): Promise<LinkPreview | null> => {
  const cached = cache.get(url);
  if (cached) return cached;

  const promise = apiClient
    .get<LinkPreview>('/linkpreview', { params: { url } })
    .then(r => r.data)
    .catch(() => null);

  cache.set(url, promise);
  return promise;
};
