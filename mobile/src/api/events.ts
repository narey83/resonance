import { apiClient } from './client';

export interface EventRecord {
  id:        string;
  timestamp: string;
  type:      string;
  data:      string;
}

export const list = (params: { offset?: number; limit?: number; type?: string; from?: string; to?: string } = {}) =>
  apiClient
    .get<EventRecord[]>('/events', { params: { offset: 0, limit: 50, ...params } })
    .then(r => r.data);
