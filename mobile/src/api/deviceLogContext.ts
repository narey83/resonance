import { getDeviceName } from '../store/auth';

// Shared by every logging path that posts to the backend (remoteLogger, debugLog, perfProbe) so
// they all tag entries with the same device identity under a single, stable "Mobile" context
// instead of each minting its own context string — resolved once per app session and cached,
// rather than round-tripping SecureStore on every log line.
let cached: Promise<string> | null = null;

export const getLogSubContext = (): Promise<string> => {
  if (!cached) cached = getDeviceName();
  return cached;
};
