// Bulk IP geolocation for the admin-only world map. Note: unlike this
// endpoint, the single-IP GET /network/lookup stays open to all users (it
// backs per-row peer flags in the regular Transfers screens), so it isn't
// duplicated here.

import { apiClient } from './client';

export interface BatchGeo {
  lat:     number;
  lon:     number;
  country: string | null;
  city:    string | null;
}

export const batchLookup = (ips: string[]) =>
  apiClient.post<Record<string, BatchGeo>>('/network/batch', ips).then(r => r.data);
