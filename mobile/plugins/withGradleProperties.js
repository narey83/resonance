const { withGradleProperties } = require('@expo/config-plugins');

// android/gradle.properties is regenerated by `expo prebuild`, so anything hand-edited into it
// silently disappears on the next prebuild and takes the build down with it. Both settings below
// were learned the hard way; keep them here, not in the generated file.
const PROPERTIES = [
  {
    // The SDK 56 default (-Xmx2048m -XX:MaxMetaspaceSize=512m) is not enough for an SDK 57 /
    // RN 0.86 release build: the daemon dies part-way through :expo-modules-core:compileReleaseKotlin
    // with a bare "Metaspace" failure. Kotlin 2.1.20 compiling this many autolinked modules needs
    // the headroom -- but only in metaspace, so the heap stays where it was. The self-hosted CI
    // runner shares a 15GB box with the dev stack and has ~6GB free, so this has to stay modest:
    // daemon + Kotlin daemon below together peak around 5GB.
    key: 'org.gradle.jvmargs',
    value: '-Xmx2048m -XX:MaxMetaspaceSize=1024m',
  },
  {
    // Kotlin compiles out of process, so its daemon is a second JVM on top of the one above and
    // needs capping too -- left to itself it sizes against total RAM, not what is actually free.
    key: 'kotlin.daemon.jvmargs',
    value: '-Xmx1536m',
  },
  {
    // Both expo-modules-core and react-native-worklets bundle libworklets.so; without this, a
    // release build fails with ":app:mergeReleaseNativeLibs FAILED -- 2 files found with path
    // lib/<abi>/libworklets.so". Either copy is fine to keep -- they're the same lib.
    key: 'android.packagingOptions.pickFirsts',
    value: '**/libworklets.so',
  },
];

module.exports = (config) =>
  withGradleProperties(config, (config) => {
    for (const { key, value } of PROPERTIES) {
      const existing = config.modResults.find(
        (item) => item.type === 'property' && item.key === key
      );
      if (existing) {
        existing.value = value;
      } else {
        config.modResults.push({ type: 'property', key, value });
      }
    }
    return config;
  });
