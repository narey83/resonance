const { withAndroidManifest } = require('@expo/config-plugins');

// Android 16 put local network access behind a runtime permission (Local Network Protection),
// and Cast discovery is nothing but mDNS multicast on that network -- so without this the
// picker comes up empty on Android 16+ while everything else about the app still works.
// play-services-cast already merges the permission into the manifest, but relying on a
// transitive merge leaves it invisible here and silently at the mercy of that dependency;
// declare it outright. Requesting it at runtime is the other half, in CastContext.
const PERMISSION = 'android.permission.ACCESS_LOCAL_NETWORK';

module.exports = (config) =>
  withAndroidManifest(config, (config) => {
    const { manifest } = config.modResults;
    const permissions = manifest['uses-permission'] ?? [];
    if (!permissions.some((p) => p.$?.['android:name'] === PERMISSION)) {
      permissions.push({ $: { 'android:name': PERMISSION } });
    }
    manifest['uses-permission'] = permissions;
    return config;
  });
